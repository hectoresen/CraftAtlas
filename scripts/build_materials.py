#!/usr/bin/env python3
"""Generate local Lua itemID-profession mapping from reviewed factual records.

The JSON input holds individual evidence and redistribution rights. A release
MUST run --release and meet the approved catalog thresholds.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "addon/CraftAtlas/Data/materials.source.json"
TARGET = ROOT / "addon/CraftAtlas/Data/Materials.lua"
PROFESSIONS = {
    "ALCHEMY", "BLACKSMITHING", "COOKING", "ENCHANTING", "ENGINEERING",
    "FIRST_AID", "LEATHERWORKING", "TAILORING",
}
HEADER = """local _, ns = ...

-- Generated with scripts/build_materials.py from audited source data.
-- Do not edit this file directly. Unknown relations are intentionally absent.
ns.materials = {
"""


def validate(records, release=False):
    errors, seen, professions, multi = [], set(), set(), 0
    for index, item in enumerate(records):
        where = f"record #{index + 1}"
        if not isinstance(item, dict):
            errors.append(f"{where}: expected object")
            continue
        item_id = item.get("itemID")
        if type(item_id) is not int or item_id <= 0 or item_id in seen:
            errors.append(f"{where}: duplicate or invalid itemID {item_id!r}")
            continue
        seen.add(item_id)
        uses = item.get("professions")
        if not isinstance(uses, list) or not uses or len(uses) != len(set(map(str, uses))):
            errors.append(f"{where}: missing or duplicate profession entries")
            continue
        if any(not isinstance(p, str) or p not in PROFESSIONS for p in uses):
            errors.append(f"{where}: unrecognized profession key")
            continue
        for required in ("source", "reviewed", "clientScope", "rights"):
            if not isinstance(item.get(required), str) or not item[required].strip():
                errors.append(f"{where}: missing {required} evidence")
        if item.get("rights") not in ("original-factual-research", "compatible-licensed-source"):
            errors.append(f"{where}: unapproved redistribution rights")
        professions.update(uses)
        if len(uses) > 1:
            multi += 1
    if release:
        if len(seen) < 30:
            errors.append(f"release requires 30 itemIDs; found {len(seen)}")
        if len(professions) < 5:
            errors.append(f"release requires 5 professions; found {len(professions)}")
        if multi < 2:
            errors.append(f"release requires 2 cross-profession materials; found {multi}")
    return errors


def generate(records):
    lines = [HEADER]
    for record in sorted(records, key=lambda x: x["itemID"]):
        profs = ", ".join('"' + p + '"' for p in sorted(record["professions"]))
        lines.append(f'    [{record["itemID"]}] = {{{profs}}},\n')
    lines.append("}\n")
    return "".join(lines)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--release", action="store_true")
    args = parser.parse_args()
    data = json.loads(SOURCE.read_text(encoding="utf-8"))
    if not isinstance(data, dict) or not isinstance(data.get("materials"), list):
        parser.error("source requires a materials array")
    records = data["materials"]
    errors = validate(records, release=args.release)
    if errors:
        parser.error("; ".join(errors))
    generated = generate(records)
    if args.check:
        if TARGET.read_text(encoding="utf-8") != generated:
            parser.error("generated Materials.lua differs from audited input")
    else:
        TARGET.write_text(generated, encoding="utf-8")
    print(f"OK: {len(records)} audited itemIDs; release={args.release}")


if __name__ == "__main__":
    main()
