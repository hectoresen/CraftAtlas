-- Pure math, independent per-view state and refresh coalescing.
local ns = {}
assert(loadfile("addon/CraftAtlas/Domain/CatalogProgress.lua"))("CraftAtlas", ns)
local empty = ns.NewCatalogProgress(0)
assert(empty.status == "complete" and ns.CatalogPercent(empty) == 100)
local materials = ns.NewCatalogProgress(593)
local recipes = ns.NewCatalogProgress(2506)
assert(ns.CatalogPercent(materials) == 0 and ns.CatalogPercent(recipes) == 0)
ns.AdvanceCatalogProgress(materials, 20, 4.5)
assert(materials.completed == 20 and ns.CatalogPercent(materials) == 3)
assert(materials.batches == 1 and materials.maxBatchMs == 4.5)
assert(recipes.completed == 0 and recipes.status == "active")
ns.AdvanceCatalogProgress(recipes, 25, 2)
assert(ns.CatalogPercent(recipes) == 0)
ns.AdvanceCatalogProgress(materials, 900, 7)
assert(ns.CatalogPercent(materials) == 100 and materials.status == "complete")
assert(materials.maxBatchMs == 7)
ns.AdvanceCatalogProgress(materials, 4)
assert(materials.completed == 593, "finished work must not restart or overflow")
ns.StopCatalogProgress(recipes)
assert(recipes.status == "incomplete" and ns.CatalogPercent(recipes) == 0)
ns.AdvanceCatalogProgress(recipes, 100)
assert(recipes.completed == 25, "stopped worker cannot fabricate completion")
assert(ns.NewCatalogProgress(-10).status == "complete")
assert(ns.NewCatalogProgress("unknown").total == 0)
local gate = ns.NewCatalogRefreshGate()
assert(ns.MarkCatalogRefreshDirty(gate) == true)
for i=1,20 do assert(ns.MarkCatalogRefreshDirty(gate) == false) end
assert(gate.pendingGeneration == 21)
assert(ns.ConsumeCatalogRefresh(gate) and gate.renders == 1)
assert(not ns.ConsumeCatalogRefresh(gate))
assert(ns.MarkCatalogRefreshDirty(gate) == true)
assert(ns.ConsumeCatalogRefresh(gate) and gate.renders == 2)
print("Catalog progress and coalesced refresh gates PASS")
